// Generates THIRD-PARTY-NOTICES.txt from what the packaged build embeds (dist\FCC).
// Run: node abas\ferramentas\gerar-avisos.js [dist\FCC] [out.txt]
const fs = require('fs'), path = require('path');
const raiz = path.resolve(__dirname, '..', '..');
const dist = path.resolve(process.argv[2] || path.join(raiz, 'dist', 'FCC'));
const saida = path.resolve(process.argv[3] || path.join(raiz, 'THIRD-PARTY-NOTICES.txt'));
const nm = path.join(dist, 'resources', 'app', 'node_modules');
if (!fs.existsSync(nm)) { console.error('missing ' + nm); process.exit(1); }

function pacotes(dir, acc) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory() || e.name === '.bin' || e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.name.startsWith('@')) { pacotes(p, acc); continue; }
    if (fs.existsSync(path.join(p, 'package.json'))) {
      acc.push(p);
      const sub = path.join(p, 'node_modules');
      if (fs.existsSync(sub)) pacotes(sub, acc);
    }
  }
  return acc;
}
const lic = (j) => {
  if (j.license) return typeof j.license === 'string' ? j.license : (j.license.type || JSON.stringify(j.license));
  if (Array.isArray(j.licenses)) return j.licenses.map((l) => l.type || l).join(' OR ');
  return 'UNKNOWN';
};
function copyright(p) {
  let nomes;
  try { nomes = fs.readdirSync(p).filter((f) => /^(licen[sc]e|copying|notice)/i.test(f)); } catch { return ''; }
  for (const f of nomes) {
    let t; try { t = fs.readFileSync(path.join(p, f), 'utf8'); } catch { continue; }
    const m = t.split(/\r?\n/).find((l) => /copyright|\(c\)|©/i.test(l) && /\d{4}|©/.test(l));
    if (m) return m.trim().slice(0, 200);
  }
  return '';
}
const lista = pacotes(nm, []).map((p) => {
  const j = JSON.parse(fs.readFileSync(path.join(p, 'package.json'), 'utf8'));
  let c = copyright(p);
  if (!c && j.author) c = 'Author: ' + (typeof j.author === 'string' ? j.author : j.author.name).replace(/\s*[<(].*$/, '');
  return { nome: j.name || path.basename(p), versao: j.version || '?', lic: lic(j), c };
}).filter((x, i, a) => a.findIndex((y) => y.nome === x.nome && y.versao === x.versao) === i)   // nested copies of the same version count once
  .map((x) => x.nome === '@anthropic-ai/claude-agent-sdk' ? { ...x, lic: 'PROPRIETARY' } : x)
  .sort((a, b) => a.nome.localeCompare(b.nome) || a.versao.localeCompare(b.versao));

const sdkLic = path.join(nm, '@anthropic-ai', 'claude-agent-sdk', 'LICENSE.md');
let termos = 'https://www.anthropic.com/legal/commercial-terms';
try { const m = fs.readFileSync(sdkLic, 'utf8').match(/https?:\/\/[^\s)>\]]+/); if (m) termos = m[0].replace(/[.,;]+$/, ''); } catch { }
let electron = '';
try { electron = fs.readFileSync(path.join(dist, 'version'), 'utf8').trim(); } catch { }

const L = [];
L.push('THIRD-PARTY NOTICES', '===================', '',
  'FCC (finjackin Claude Center) is distributed as a packaged Electron application.',
  'This file lists the third-party components embedded in that package. Generated by',
  'abas/ferramentas/gerar-avisos.js from dist/FCC; rerun it after changing dependencies.', '',
  '1. Electron / Chromium' + (electron ? ' (Electron ' + electron + ')' : ''), '----------------------',
  'The package ships the Electron runtime, which bundles Chromium, Node.js, V8, FFmpeg and',
  'other components under their own licenses. See the files shipped inside the package:',
  '  - LICENSE-ELECTRON.txt (Electron, MIT License, Copyright (c) Electron contributors / GitHub Inc.)',
  '  - LICENSES.chromium.html (full list of Chromium and bundled third-party licenses)', '',
  '2. PROPRIETARY COMPONENT', '------------------------',
  '@anthropic-ai/claude-agent-sdk is NOT open source. It is proprietary software:',
  '  (c) Anthropic PBC. All rights reserved.',
  '  Use is subject to Anthropic\'s terms: ' + termos,
  '  It is not covered by this project\'s license and is not relicensed by it.',
  '  FCC\'s GPLv3 license grants an additional permission to combine FCC with it: see LICENSE-EXCEPTION.txt.', '',
  '3. npm packages in resources/app/node_modules (' + lista.length + ')', '-----------------------------------------------------');
for (const x of lista) L.push(x.nome + '@' + x.versao + ' | ' + (x.lic === 'PROPRIETARY' ? 'PROPRIETARY (see section 2)' : x.lic) + (x.c ? ' | ' + x.c : ''));
L.push('');
const cont = {}; for (const x of lista) cont[x.lic] = (cont[x.lic] || 0) + 1;
L.push('License summary: ' + Object.entries(cont).sort((a, b) => b[1] - a[1]).map(([k, v]) => k + ' x' + v).join(', '), '');
fs.writeFileSync(saida, L.join('\n'), 'utf8');
console.log('wrote ' + saida + ' (' + lista.length + ' packages)');
